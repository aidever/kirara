#!/usr/bin/env python3
"""Sync PT-depiler site identities into kirara.

Updates two hand-maintained tables from a local PT-depiler checkout:

  * ``src/ptd_sites.rs``        host -> PTD site id (``urls`` + ``legacyUrls``)
  * ``src/ptd_site_catalog.rs`` site presets that kirara can add / import

Existing host mappings and presets are kept (PTD drops hosts of dead sites, but
users may still have those sites configured). New hosts are added, and a host
that PTD now assigns to another site id follows PTD. Presets are only appended
for live private sites whose schema has a kirara adapter.

Usage:
  git clone --depth 1 https://github.com/pt-plugins/PT-depiler.git /tmp/ptd
  python tools/sync_ptd_sites.py --local /tmp/ptd/src/packages/site/definitions \\
      --commit "$(git -C /tmp/ptd rev-parse HEAD)"
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_ptd_site_rules as g  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SITES_RS = ROOT / "src/ptd_sites.rs"
CATALOG_RS = ROOT / "src/ptd_site_catalog.rs"

# PTD schema (or base class) -> kirara site_type.
SCHEMA_SITE_TYPES = {
    "NexusPHP": "nexusphp",
    "Unit3D": "unit3d",
    "Rousi": "rousi",
    "TNode": "tnode",
    "SunnyPT": "sunnypt",
}


def site_meta(path: Path) -> dict | None:
    source = path.read_text(encoding="utf-8")
    body = g.find_site_metadata(source)
    if body is None:
        return None
    props = g.object_properties(source, body[0], body[1])

    def strings(key: str) -> list[str]:
        values = g.array_strings(source, props.get(key))
        return [g.rot13(v) if v.startswith(("uggcf://", "uggc://")) else v for v in values]

    dead = props.get("isDead")
    schema = g.property_string(source, props, "schema")
    if not schema:
        match = re.search(r"extends (NexusPHP|Unit3D)\b", source)
        schema = match.group(1) if match else None
    return {
        "id": g.property_string(source, props, "id") or path.stem,
        "name": g.property_string(source, props, "name") or path.stem,
        "schema": schema,
        "type": g.property_string(source, props, "type"),
        "urls": strings("urls"),
        "legacy": strings("legacyUrls"),
        "aka": strings("aka"),
        "dead": dead is not None and source[dead[0] : dead[1]].strip().startswith("true"),
    }


def host_of(url: str) -> str | None:
    host = re.sub(r"^[a-z]+://", "", url.strip().lower()).split("/")[0].split(":")[0]
    host = host.removeprefix("www.").rstrip(".")
    return host if "." in host else None


def parse_existing_hosts(source: str) -> dict[str, str]:
    hosts: dict[str, str] = {}
    body = source[source.index("match host {") : source.index("_ => None")]
    for arm in re.finditer(r"((?:\s*\|?\s*\"[^\"]+\")+)\s*=>\s*Some\(\"([^\"]+)\"\)", body):
        for host in re.findall(r"\"([^\"]+)\"", arm.group(1)):
            hosts[host] = arm.group(2)
    return hosts


def emit_sites(hosts: dict[str, str], commit: str, old_source: str) -> str:
    by_id: dict[str, list[str]] = defaultdict(list)
    for host, site_id in hosts.items():
        by_id[site_id].append(host)
    arms = []
    for site_id in sorted(by_id):
        names = " | ".join(f'"{h}"' for h in sorted(by_id[site_id]))
        arms.append(f'        {names} => Some("{site_id}"),')
    tests = old_source[old_source.index("#[cfg(test)]") :]
    return (
        "//! PT-Depiler canonical site identifiers keyed by their known host names.\n"
        "//!\n"
        "//! Generated by `tools/sync_ptd_sites.py` from PT-Depiler site definitions at commit\n"
        f"//! `{commit}`. Hosts of sites PTD has since removed are kept.\n"
        "\n"
        "pub fn site_id_for_host(host: &str) -> Option<&'static str> {\n"
        "    let host = host.trim_end_matches('.');\n"
        "    let host = host.strip_prefix(\"www.\").unwrap_or(host);\n"
        "    match host {\n" + "\n".join(arms) + "\n        _ => None,\n    }\n}\n\n" + tests
    )


def rust_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit_preset(meta: dict, site_type: str) -> str:
    base = meta["urls"][0].rstrip("/")
    aliases = ", ".join(rust_str(a) for a in meta["aka"])
    return (
        "    PtdSitePreset {\n"
        f"        ptd_id: {rust_str(meta['id'])},\n"
        f"        name: {rust_str(meta['name'])},\n"
        f"        site_type: {rust_str(site_type)},\n"
        f"        base_url: {rust_str(base)},\n"
        f"        aliases: &[{aliases}],\n"
        "    },\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--local", type=Path, required=True)
    parser.add_argument("--commit", required=True)
    args = parser.parse_args()

    metas = [m for p in sorted(args.local.glob("*.ts")) if (m := site_meta(p))]

    old_sites = SITES_RS.read_text(encoding="utf-8")
    hosts = parse_existing_hosts(old_sites)
    added_hosts = []
    for meta in metas:
        for url in meta["urls"] + meta["legacy"]:
            host = host_of(url)
            if host and hosts.get(host) != meta["id"]:
                added_hosts.append(f"{host} -> {meta['id']}")
                hosts[host] = meta["id"]
    SITES_RS.write_text(emit_sites(hosts, args.commit, old_sites), encoding="utf-8")

    catalog = CATALOG_RS.read_text(encoding="utf-8")
    existing = set(re.findall(r'ptd_id: "([^"]+)"', catalog))
    added_presets = []
    new_entries = ""
    for meta in metas:
        site_type = SCHEMA_SITE_TYPES.get(meta["schema"] or "")
        if (
            site_type is None
            or meta["type"] != "private"
            or meta["dead"]
            or not meta["urls"]
            or meta["id"] in existing
        ):
            continue
        new_entries += emit_preset(meta, site_type)
        added_presets.append(f"{meta['id']} ({site_type})")
    # A preset still pointing at a host PTD moved to legacyUrls follows the site's new home.
    moved_presets = []
    by_id = {meta["id"]: meta for meta in metas}

    def follow_move(match: re.Match[str]) -> str:
        meta = by_id.get(match.group(1))
        base = match.group(2).rstrip("/")
        if not meta or meta["dead"] or not meta["urls"]:
            return match.group(0)
        if base + "/" not in meta["legacy"] and base not in meta["legacy"]:
            return match.group(0)
        new_base = meta["urls"][0].rstrip("/")
        moved_presets.append(f"{meta['id']}: {base} -> {new_base}")
        return match.group(0).replace(f'base_url: "{match.group(2)}"', f'base_url: "{new_base}"')

    catalog = re.sub(
        r'ptd_id: "([^"]+)",\s*name: "[^"]*",\s*site_type: "[^"]+",\s*base_url: "([^"]+)"',
        follow_move,
        catalog,
    )
    if new_entries:
        end = catalog.rindex("];")
        catalog = catalog[:end] + new_entries + catalog[end:]
    catalog = re.sub(
        r"//! Generated from PT-Depiler site definitions at commit\n//! `[^`]+`[^\n]*",
        "//! Generated from PT-Depiler site definitions; synced by `tools/sync_ptd_sites.py`\n"
        f"//! at commit `{args.commit}`.",
        catalog,
        count=1,
    )
    CATALOG_RS.write_text(catalog, encoding="utf-8")

    print(f"hosts added/changed: {len(added_hosts)}", file=sys.stderr)
    for line in added_hosts:
        print(f"  {line}", file=sys.stderr)
    print(f"presets moved: {len(moved_presets)}", file=sys.stderr)
    for line in moved_presets:
        print(f"  {line}", file=sys.stderr)
    print(f"presets added: {len(added_presets)}", file=sys.stderr)
    for line in added_presets:
        print(f"  {line}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
